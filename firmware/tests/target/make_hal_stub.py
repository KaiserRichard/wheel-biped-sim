"""Generate the constants-only part of the local HAL fixture; no vendor dependency."""
import re
from pathlib import Path
root = Path(__file__).resolve().parents[2]
files = ['target_fdcan.c', 'target_crsf.c', 'target_usb_cdc.c', 'target_estop.c', 'target_iwdg.c', 'target_safety_io.c', 'target_hw.h']
source = '\n'.join((root / 'firmware/target' / x).read_text() for x in files)
names = sorted(set(re.findall(r'\b(?:FDCAN_|GPIO_|UART_|RCC_|IWDG_|PCD_|USB_OTG_|EP_TYPE_)[A-Z0-9_]+\b', source)))
special = {'GPIO_PIN_RESET': 0, 'GPIO_PIN_SET': 1, 'FDCAN_DLC_BYTES_8': 8 << 16, 'USB_OTG_MAX_EP0_SIZE': 64}
for prefix in ['FDCAN_IT_', 'RCC_FLAG_']:
    for i, name in enumerate(x for x in names if x.startswith(prefix)):
        special[name] = 1 << i
for name in names:
    if re.fullmatch(r'GPIO_PIN_\d+', name):
        special[name] = 1 << int(name.rsplit('_', 1)[1])
    if re.fullmatch(r'FDCAN_TX_BUFFER\d+', name):
        special[name] = 1 << int(name[-1])
(root / 'tests/target/hal_stub_constants.h').write_text('/* Generated by make_hal_stub.py; test values, not silicon values. */\n' + '\n'.join(f'#define {x} {special.get(x, i + 100)}u' for i, x in enumerate(names)) + '\n')
